#!/usr/bin/env python3
"""carve.py -- ufs and s5 out of the kernel, as core-tier modules (S5-04;
docs/plan/s4-40-ufs-s5-carve.md, contract C4-6).

  carve.py wrap --fs ufs|s5 --obj STOCK --filesys FILESYS.o --build ID OUT
      A module directory for the ABI kit (KIT=... make -C OUT): a
      generated wrapper (MOD_MISC_WRAPPER; _load registers the type with
      vfs_register, s5 calling inoinit first), a Master (class boot,
      match always, tier core, the cut's build id, fs=, unload never, the
      probe parameter) and the stock object linked in as it is (EXTRA).
      The row's vsw_flag is read from the stock vfssw in FILESYS.o.

  carve.py corelist --ddi DDI.list --namelist KERNEL --tree SYS OBJ...
      The core tier for the carved objects (C3-2 section 4), sorted, in
      the list format: every name they import outside DDI, and every
      COMMON they share with another stock object under SYS (those stay
      the kernel's; the others go with the modules).  The kind (func or
      data) is the namelist's.

With probe=1 the wrapper prints the level and whether lbolt moved around
each init call, as tests/bench/s4-71 does (S4-71's ufs/s5 halves).  The
stock objects are read, never copied into this tree.

Copyright (c) 2026 Jussi Alanärä.  MIT licence, see LICENSE.
"""
import os
import struct
import sys

SHN_UNDEF, SHN_COMMON = 0, 0xfff2


class Elf:
    """the symbols and relocations of an ELF32 big-endian file"""

    def __init__(self, path):
        d = self.d = open(path, 'rb').read()
        if d[:4] != b'\x7fELF' or d[4] != 1 or d[5] != 2:
            raise SystemExit('carve: %s is not ELF32 big-endian' % path)
        shoff, = struct.unpack('>I', d[32:36])
        shnum, shstrndx = struct.unpack('>HH', d[48:52])
        self.sh = [struct.unpack('>10I', d[shoff + 40 * i:shoff + 40 * i + 40])
                   for i in range(shnum)]
        self.syms = []
        for s in self.sh:
            if s[1] in (2, 11):		# SYMTAB, DYNSYM
                strs = self.sh[s[6]]
                for o in range(s[4], s[4] + s[5], 16):
                    nm, val, size, info, other, shndx = struct.unpack('>IIIBBH', d[o:o + 16])
                    self.syms.append((self.str(strs, nm), val, size, info, shndx))
                break

    def str(self, sec, off):
        o = sec[4] + off
        return self.d[o:self.d.index(b'\0', o)].decode('latin1')

    def globals(self):
        return [s for s in self.syms if s[3] >> 4 in (1, 2) and s[0]]

    def undefined(self):
        return {s[0] for s in self.globals() if s[4] == SHN_UNDEF}

    def commons(self):
        return {s[0] for s in self.globals() if s[4] == SHN_COMMON}

    def defined(self):
        return {s[0]: s for s in self.globals() if s[4] not in (SHN_UNDEF, SHN_COMMON)}

    def rela(self, target):
        """(offset, symbol name, addend) of the relocations into section target"""
        out = []
        for s in self.sh:
            if s[1] in (4, 9) and s[7] == target:		# RELA, REL
                ent = 12 if s[1] == 4 else 8
                for o in range(s[4], s[4] + s[5], ent):
                    off, info = struct.unpack('>II', self.d[o:o + 8])
                    add = struct.unpack('>i', self.d[o + 8:o + 12])[0] if ent == 12 else 0
                    out.append((off, self.syms[info >> 8][0], add))
        return out


def vsw_flag(filesys, init):
    """the stock vfssw row whose init is init: its vsw_flag"""
    e = Elf(filesys)
    vs = e.defined().get('vfssw')
    if not vs:
        raise SystemExit('carve: %s defines no vfssw' % filesys)
    sec = e.sh[vs[4]]
    for off, name, _ in e.rela(vs[4]):
        if name == init and vs[1] <= off < vs[1] + vs[2] and (off - vs[1]) % 16 == 4:
            row = sec[4] + off - 4
            return struct.unpack('>i', e.d[row + 12:row + 16])[0]
    raise SystemExit('carve: no vfssw row of %s calls %s' % (filesys, init))


FS = {	# the type, its init, its vfsops, what _load calls first
    'ufs': ('ufsinit', 'ufs_vfsops', None),
    's5': ('s5init', 's5vfsops', 'inoinit'),
}

WRAPPER = '''/*
 * %(fs)s_wrap.c -- generated by tools/carve.py (S5-04): the %(fs)s module's
 * wrapper.  _load registers the type (vfs_register, contract C4-6
 * section 3)%(first_doc)s; with probe=1 it prints the level and whether
 * lbolt moved around each init call (S4-71's ufs/s5 halves).
 */
#include "sys/types.h"
#include "sys/errno.h"
#include "sys/moddefs.h"
#include "sys/amixddi.h"

extern int	%(init)s(), printf();%(first_decl)s
extern char	%(ops)s[];
extern long	lbolt;

static int	probe;

static int
level()
{
	unsigned short s;

	__asm__ __volatile__("movew %%%%sr,%%0" : "=d" (s));
	return (s >> 8) & 7;
}

static void
said(what, lb)
	char *what;
	long lb;
{
	if (probe)
		printf("%(fs)s: %%s, level %%d, lbolt %%s\\n", what, level(),
		    lbolt == lb ? "unmoved" : "MOVED");
}

/* the row's init, as vfsinit would call it */
static int
%(fs)s_init(vswp, idx)
	char *vswp;
	int idx;
{
	long lb = lbolt;
	int r;

	said("%(init)s entered", lb);
	r = %(init)s(vswp, idx);
	said("%(init)s returned", lb);
	return r;
}

static int
%(fs)s_load(params)
	char *params;
{
	char *p;

	for (p = params; p && *p; p++)
		if ((p == params || p[-1] == ' ') && p[0] == 'p' && p[1] == 'r' && p[2] == 'o' &&
		    p[3] == 'b' && p[4] == 'e' && p[5] == '=' && p[6] == '1')
			probe = 1;
%(first_call)s	return vfs_register("%(fs)s", %(fs)s_init, (struct vfsops *)%(ops)s, %(flag)dL);
}

static int
%(fs)s_unload()
{
	return EBUSY;		/* unload=never: a mounted type stays */
}

MOD_MISC_WRAPPER(%(fs)s, %(fs)s_load, %(fs)s_unload, "%(fs)s filesystem (carved)");
'''

FIRST = '''	{
		long lb = lbolt;

		said("%(first)s entered", lb);
		%(first)s();
		said("%(first)s returned", lb);
	}
'''


def wrap(args):
    opt = dict(zip(args[0:-1:2], args[1:-1:2]))
    out = args[-1]
    fs = opt.get('--fs')
    if fs not in FS or not all(k in opt for k in ('--obj', '--filesys', '--build')):
        raise SystemExit('usage: carve.py wrap --fs ufs|s5 --obj STOCK --filesys FILESYS.o --build ID OUT')
    init, ops, first = FS[fs]
    body = Elf(opt['--obj'])
    for need in (init, ops) + ((first,) if first else ()):
        if need not in body.defined():
            raise SystemExit('carve: %s does not define %s' % (opt['--obj'], need))
    flag = vsw_flag(opt['--filesys'], init)
    os.makedirs(out, exist_ok=True)
    v = {'fs': fs, 'init': init, 'ops': ops, 'flag': flag,
         'first_doc': ', after %s' % first if first else '',
         'first_decl': '\nextern int\t%s();' % first if first else '',
         'first_call': FIRST % {'first': first} if first else ''}
    open(os.path.join(out, fs + '_wrap.c'), 'w').write(WRAPPER % v)
    open(os.path.join(out, 'Master'), 'w').write(
        '# %s: carved by tools/carve.py (S5-04), core tier, built per kernel cut\n'
        '$modtype misc\n$class boot\n$match always\n$tier core\n$build %s\n$fs %s\n'
        '$unload never\n$param probe:bool:0\n$desc %s filesystem (carved)\n%s\t%s\n'
        % (fs, opt['--build'], fs, fs, fs, fs))
    open(os.path.join(out, 'Makefile'), 'w').write(
        '# the %s module, carved (tools/carve.py): make KIT=<amix-dlm>/build/kit/<line>\n'
        'MODULE = %s\nOBJS = %s_wrap.o\nEXTRA = %s\ninclude $(KIT)/mk/module.mk\n'
        % (fs, fs, fs, os.path.abspath(opt['--obj'])))
    print('carve: %s: %s wraps %s (vfs_register flag %d, build %s)'
          % (fs, out, opt['--obj'], flag, opt['--build']))


def corelist(args):
    opt, objs = {}, []
    i = 0
    while i < len(args):
        if args[i] in ('--ddi', '--namelist', '--tree'):
            opt[args[i]] = args[i + 1]
            i += 2
        else:
            objs.append(args[i])
            i += 1
    if len(opt) != 3 or not objs:
        raise SystemExit('usage: carve.py corelist --ddi DDI.list --namelist KERNEL --tree SYS OBJ...')
    ddi = set()
    for line in open(opt['--ddi']):
        w = line.split('#')[0].split()
        if w:
            ddi.add(w[0])
    carved = [Elf(o) for o in objs]
    own = set()
    for e in carved:
        own |= set(e.defined())
    imports = set()
    for e in carved:
        imports |= e.undefined()
    imports -= own
    commons = set()
    for e in carved:
        commons |= e.commons()
    # a COMMON another stock object also names stays the kernel's
    others = set()
    real = {os.path.realpath(o) for o in objs}
    for root, _, files in os.walk(opt['--tree']):
        for f in files:
            p = os.path.join(root, f)
            if os.path.realpath(p) in real or not (f == 'exp' or f.endswith('.o')):
                continue
            try:
                e = Elf(p)
            except (SystemExit, struct.error, ValueError, IndexError):
                continue
            others |= e.undefined() | e.commons() | set(e.defined())
    shared = commons & others
    kern = Elf(opt['--namelist'])
    kinds = {}
    for s in kern.globals():
        if s[4] != SHN_UNDEF:
            kinds[s[0]] = 'func' if s[3] & 15 == 2 else 'data'
    names = sorted((imports | shared) - ddi)
    missing = [n for n in names if n not in kinds]
    if missing:
        raise SystemExit('carve: not in the kernel namelist: %s' % ' '.join(missing))
    for n in names:
        print('%s %s 2' % (n, kinds[n]))
    print('carve: %d core-tier names: %d imports outside DDI, %d shared COMMONs; '
          '%d COMMONs go with the modules' % (len(names), len(imports - ddi), len(shared - ddi),
                                             len(commons - shared)), file=sys.stderr)


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ('wrap', 'corelist'):
        raise SystemExit(__doc__.split('\n\n')[1])
    (wrap if sys.argv[1] == 'wrap' else corelist)(sys.argv[2:])


if __name__ == '__main__':
    main()
