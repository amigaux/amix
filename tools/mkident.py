#!/usr/bin/env python3
# mkident.py -- a module kernel's identity record (AXK1,
# docs/contracts/C3-3-kernel-identity.md) and its module arena (C3-4).
#
#   mkident.py --asm LINE KABI CAP > ident.s
#       dlm_ident (64 bytes: magic, version, kabi tag, line, flags; the
#       offsets and the check still 0) and dlm_arena (CAP zero bytes), both
#       4-byte aligned in .data (.data follows .text directly in the
#       loader's layout; boot2 aligns each module's bytes itself, C3-4).
#   mkident.py --fill KERNEL
#       after the final link (ET_REL, as shipped; on the 030 line the .etrel
#       before elf2brel): the arena's and the symbol block's image offsets
#       (from the bind address, in the loader's layout: text, rodata, data,
#       no padding) and their sizes into dlm_ident, and its check; prints
#       the sidecar's ident=, arena= and ksym= lines (C2-3 version 5).
#   mkident.py --check KERNEL
#       the record as boot2 and the core check it, against the kernel's own
#       symbols; exit status 1 if anything is off.
#
# Copyright (c) 2026 Jussi Alanärä.  MIT licence, see LICENSE.
import struct, sys

MAGIC, VERLEN = 0x41584b31, (1 << 16) | 64


def u32(b, o):
    return struct.unpack('>I', b[o:o + 4])[0]


def asm(line, kabi, cap):
    if line not in ('k30', 'k46') or len(kabi) > 23 or not kabi.startswith(line + '.'):
        sys.exit('mkident: line k30 or k46, and a kabi tag of that line (k46.1.0)')
    if cap % 0x10000:
        sys.exit('mkident: the arena capacity is a multiple of 64 KiB')
    tag = kabi.encode().ljust(24, b'\0')
    words = ', '.join('0x%08x' % u32(tag, i) for i in range(0, 24, 4))
    print('| generated by tools/mkident.py --asm %s %s 0x%x: the identity record (C3-3)\n'
          '| and the module arena (C3-4); the offsets and the check are filled after\n'
          '| the final link by mkident.py --fill\n'
          '\t.data\n\t.balign\t4\n\t.globl\tdlm_ident\n\t.type\tdlm_ident,@object\n'
          '\t.size\tdlm_ident,64\ndlm_ident:\n'
          '\t.long\t0x%08x, 0x%08x, 0\n'
          '\t.long\t%s\n'
          '\t.long\t%d, 0, 0x%x, 0, 0, 1, 0\n'
          '\t.balign\t4\n\t.globl\tdlm_arena\n\t.type\tdlm_arena,@object\n'
          '\t.size\tdlm_arena,%d\ndlm_arena:\n\t.space\t%d'
          % (line, kabi, cap, MAGIC, VERLEN, words, int(line[1:]), cap, cap, cap))


def parse(path):
    b = bytearray(open(path, 'rb').read())
    if b[:4] != b'\x7fELF' or struct.unpack('>H', b[16:18])[0] != 1:
        sys.exit('mkident: %s is not an ELF relocatable' % path)
    shoff, = struct.unpack('>I', b[32:36])
    shnum, = struct.unpack('>H', b[48:50])
    sh = [struct.unpack('>10I', b[shoff + 40 * i:shoff + 40 * i + 40]) for i in range(shnum)]
    defs = {}
    for s in sh:
        if s[1] == 2:
            st = sh[s[6]][4]
            for k in range(s[5] // 16):
                o = s[4] + 16 * k
                nm, val, sz, info, oth, shn = struct.unpack('>IIIBBH', b[o:o + 16])
                name = b[st + nm:b.index(b'\0', st + nm)].decode('latin-1')
                if name and shn not in (0, 0xfff1, 0xfff2) and info >> 4:
                    defs[name] = (val, sz, shn)
    # the loader's layout (loader/common/rel.c): the last section of each kind wins
    t = r = d = None
    for i, s in enumerate(sh):
        if s[1] == 1 and s[5] and s[2] & 2:
            if s[2] & 4:
                t = i
            elif s[2] & 1:
                d = i
            else:
                r = i
    base, at = {}, 0
    for i in (t, r, d):
        if i is not None:
            base[i] = at
            at += sh[i][5]
    return b, sh, defs, base


def where(sh, defs, base, name):
    """image offset and file offset of a .data symbol"""
    if name not in defs:
        sys.exit('mkident: the kernel defines no %s' % name)
    val, sz, shn = defs[name]
    if shn not in base or sh[shn][1] != 1:
        sys.exit('mkident: %s is not in text, rodata or data' % name)
    return base[shn] + val, sh[shn][4] + val, sz


def fill(path):
    b, sh, defs, base = parse(path)
    _, idf, idsz = where(sh, defs, base, 'dlm_ident')
    aimg, _, asz = where(sh, defs, base, 'dlm_arena')
    kimg, _, ksz = where(sh, defs, base, 'dlm_ksym')
    if idsz != 64 or u32(b, idf) != MAGIC or u32(b, idf + 4) != VERLEN:
        sys.exit('mkident: dlm_ident is not the record mkident.py --asm wrote')
    if u32(b, idf + 44) != asz:
        sys.exit('mkident: dlm_arena is %d bytes, the record says %d' % (asz, u32(b, idf + 44)))
    struct.pack_into('>I', b, idf + 40, aimg)
    struct.pack_into('>II', b, idf + 48, kimg, ksz)
    struct.pack_into('>I', b, idf + 8, 0)
    s = sum(u32(b, idf + 4 * i) for i in range(16))
    struct.pack_into('>I', b, idf + 8, (0 - s) & 0xffffffff)
    open(path, 'wb').write(b)
    print('ident=0x%08x' % where(sh, defs, base, 'dlm_ident')[0])
    print('arena=0x%08x 0x%08x' % (aimg, asz))
    print('ksym=0x%08x 0x%08x' % (kimg, ksz))


def check(path):
    b, sh, defs, base = parse(path)
    idimg, idf, idsz = where(sh, defs, base, 'dlm_ident')
    aimg, _, asz = where(sh, defs, base, 'dlm_arena')
    kimg, _, ksz = where(sh, defs, base, 'dlm_ksym')
    r = bytes(b[idf:idf + 64])
    bad = []
    if u32(r, 0) != MAGIC or u32(r, 4) != VERLEN:
        bad.append('magic or version')
    if sum(u32(r, 4 * i) for i in range(16)) & 0xffffffff:
        bad.append('the check')
    kabi = r[12:36].rstrip(b'\0').decode('latin-1')
    if u32(r, 36) not in (30, 46) or not kabi.startswith('k%d.' % u32(r, 36)):
        bad.append('line or kabi tag')
    if u32(r, 40) != aimg or u32(r, 44) != asz:
        bad.append('arena offset or capacity')
    if u32(r, 48) != kimg or u32(r, 52) != ksz:
        bad.append('symbol block offset or size')
    if u32(r, 56) != 1:
        bad.append('flags')
    if bad:
        print('mkident: %s: %s' % (path, ', '.join(bad)))
        sys.exit(1)
    print('mkident: %s: AXK1 at 0x%08x, %s, arena 0x%08x 0x%x, symbol block 0x%08x %d bytes'
          % (path, idimg, kabi, aimg, asz, kimg, ksz))


if len(sys.argv) == 5 and sys.argv[1] == '--asm':
    asm(sys.argv[2], sys.argv[3], int(sys.argv[4], 0))
elif len(sys.argv) == 3 and sys.argv[1] == '--fill':
    fill(sys.argv[2])
elif len(sys.argv) == 3 and sys.argv[1] == '--check':
    check(sys.argv[2])
else:
    sys.exit('usage: mkident.py --asm LINE KABI CAP | --fill KERNEL | --check KERNEL')
