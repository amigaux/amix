# build-amix.sh - cross-build heirloom-pkgtools for Amiga Unix
# (Amix 2.1c, SVR4.0 m68k) with the gcc-cross-amix toolchain.
#
# Replicates the stock build scheme (per-directory Makefile generated
# by concatenating a config fragment with the directory's Makefile.mk),
# using mk.config.amix instead of mk.config and prepending TOPDIR so
# that compat/ and sslstub/ resolve from any subdirectory.
#
# The m68k-cbm-sysv4-gcc driver is a wrapper script with three quirks
# this build must work around (see AMIX-PORT.md for details):
#   1. it force-prepends -I$AMIX_SYSROOT/usr/include BEFORE all user
#      -I flags, and the real sysroot contains the stock SVR4 pkg
#      headers (pkgstrct.h, pkginfo.h, ...) which would shadow
#      heirloom's hdrs/ copies;
#   2. it does not pass -include through (so amixcompat.h cannot be
#      force-included on the command line);
#   3. it never links libgcc (none exists in the toolchain), and links
#      libc automatically only when NO -l flags are given.
# Workarounds: a generated SHADOW SYSROOT (build-amix/sysroot) that
# omits the conflicting pkg headers and wraps five common headers to
# chain-include compat/amixcompat.h; a replacement libgcc.a built from
# compat/di_ops.c; and explicit "-lgcc -lc" in LIBS (mk.config.amix).
#
# Output:
#   build-amix/bin/            pkginfo pkgparam pkgtrans pkgadd(+pkgask)
#                              pkgrm installf(+removef) pkgchk pkgmk pkgproto
#   build-amix/sadm-helpers/   pkginstall pkgremove  (deploy to
#                              /usr/apkg/sadm/install/bin on the guest)
#
# NOTE: this regenerates every <dir>/Makefile and runs "make clean"
# first, so it cannot be mixed with an in-flight build-host.sh build
# (each script rebuilds from scratch; the final binaries are copied
# out into their respective build-*/ trees, which do coexist).
#
set -eu

TOP="$(cd "$(dirname "$0")" && pwd)"
# Default: a gcc-cross-amix checkout beside this repo (set AMIX_CROSS_ENV
# to point elsewhere).
CROSS_ENV="${AMIX_CROSS_ENV:-$TOP/../../gcc-cross-amix/build/env.sh}"

if ! command -v m68k-cbm-sysv4-gcc >/dev/null 2>&1; then
	if [ -r "$CROSS_ENV" ]; then
		# shellcheck disable=SC1090
		. "$CROSS_ENV"
	fi
fi
command -v m68k-cbm-sysv4-gcc >/dev/null 2>&1 || {
	echo "build-amix.sh: m68k-cbm-sysv4-gcc not in PATH (set AMIX_CROSS_ENV)" >&2
	exit 1
}

REAL_SYSROOT="${AMIX_SYSROOT:-$HOME/opt/amix-cross/m68k-cbm-sysv4/sysroot}"
[ -d "$REAL_SYSROOT/usr/include" ] || {
	echo "build-amix.sh: real sysroot not found at $REAL_SYSROOT" >&2
	exit 1
}

# ------------------------------------------------------------------
# 1. Fresh build-amix/ work area
# ------------------------------------------------------------------
rm -rf "$TOP/build-amix"
SHADOW="$TOP/build-amix/sysroot"
mkdir -p "$TOP/build-amix/bin" "$TOP/build-amix/sadm-helpers" \
	 "$TOP/build-amix/lib" "$SHADOW/usr/include/sys"

# ------------------------------------------------------------------
# 2. Shadow sysroot
#    - usr/lib and usr/ccs pass through to the real sysroot
#    - usr/include: symlink farm of the real headers, EXCEPT
#        * any name heirloom provides in hdrs/ (or hdrs/sys/) - the
#          stock SVR4 pkg headers must not shadow heirloom's own;
#        * five wrapped headers, generated below, which chain to the
#          real header and then pull in compat/amixcompat.h (the
#          "force-include" replacement).
# ------------------------------------------------------------------
ln -s "$REAL_SYSROOT/usr/lib" "$SHADOW/usr/lib"
ln -s "$REAL_SYSROOT/usr/ccs" "$SHADOW/usr/ccs"

WRAPPED_TOP="stdio.h stdlib.h string.h ctype.h"
WRAPPED_SYS="types.h signal.h"

is_in() {
	local x="$1"; shift
	local i
	for i in "$@"; do [ "$x" = "$i" ] && return 0; done
	return 1
}

# top-level include entries
for e in "$REAL_SYSROOT/usr/include"/*; do
	n="$(basename "$e")"
	[ "$n" = "sys" ] && continue			# handled member-wise
	[ -e "$TOP/hdrs/$n" ] && continue		# heirloom's hdrs/ wins
	is_in "$n" $WRAPPED_TOP && continue		# wrapper generated below
	ln -s "$e" "$SHADOW/usr/include/$n"
done

# sys/ include entries
for e in "$REAL_SYSROOT/usr/include/sys"/*; do
	n="$(basename "$e")"
	[ -e "$TOP/hdrs/sys/$n" ] && continue		# heirloom's hdrs/sys wins
	is_in "$n" $WRAPPED_SYS && continue
	ln -s "$e" "$SHADOW/usr/include/sys/$n"
done

# wrapped headers: real header first, then the compat shim
for n in $WRAPPED_TOP; do
	guard="AMIX_SHADOW_$(echo "$n" | tr 'a-z./' 'A-Z__')"
	cat > "$SHADOW/usr/include/$n" <<EOF
/* generated by build-amix.sh - do not edit */
#ifndef $guard
#define $guard
#include "$REAL_SYSROOT/usr/include/$n"
#include "$TOP/compat/amixcompat.h"
#endif
EOF
done
for n in $WRAPPED_SYS; do
	guard="AMIX_SHADOW_SYS_$(echo "$n" | tr 'a-z./' 'A-Z__')"
	if [ "$n" = "signal.h" ]; then
		# sys/signal.h guards sigset_t/struct sigaction with
		# "(__STDC__ - 0 == 0) || defined(_POSIX_SOURCE)"; gcc has
		# __STDC__=1 and a global _POSIX_SOURCE would hide SVR4
		# extras elsewhere, so define it for this header only.
		cat > "$SHADOW/usr/include/sys/$n" <<EOF
/* generated by build-amix.sh - do not edit */
#ifndef $guard
#define $guard
#ifdef _POSIX_SOURCE
#include "$REAL_SYSROOT/usr/include/sys/$n"
#else
#define _POSIX_SOURCE 1
#include "$REAL_SYSROOT/usr/include/sys/$n"
#undef _POSIX_SOURCE
#endif
#include "$TOP/compat/amixcompat.h"
#endif
EOF
		continue
	fi
	cat > "$SHADOW/usr/include/sys/$n" <<EOF
/* generated by build-amix.sh - do not edit */
#ifndef $guard
#define $guard
#include "$REAL_SYSROOT/usr/include/sys/$n"
#include "$TOP/compat/amixcompat.h"
#endif
EOF
done

export AMIX_SYSROOT="$SHADOW"
export AMIX_CRT_DIR="$REAL_SYSROOT/usr/ccs/lib"

# ------------------------------------------------------------------
# 3. Replacement libgcc.a (64-bit integer helpers, compat/di_ops.c)
# ------------------------------------------------------------------
echo "== building runtime support archive (libamix.a) =="
# Contents:
#  - di_ops.o: 64-bit integer helpers (the toolchain ships no libgcc.a)
#  - getutx.o, getut.o: extracted from the STATIC SVR4.0 libc.a; the
#    shared libc.so.1 does not export the getutx*() family which
#    pkginstall's run-level check calls (closure verified: everything
#    else these two members need resolves in libc.so.1)
# (host ar/ranlib: the binutils-2.8.1 cross ar aborts on modern glibc)
( cd "$TOP/build-amix/lib" &&
  "$TOP/amix-cc" -O -c "$TOP/compat/di_ops.c" -o di_ops.o &&
  ar x "$REAL_SYSROOT/usr/ccs/lib/libc.a" getutx.o getut.o truncate.o &&
  ar rc libamix.a di_ops.o getutx.o getut.o truncate.o &&
  ranlib libamix.a )

# ------------------------------------------------------------------
# 4. Generate per-directory Makefiles and build
# ------------------------------------------------------------------
SUBDIRS="version libadm libgendb libpkg libinst
	pkgcmds/pkginfo pkgcmds/pkgparam pkgcmds/pkgtrans
	pkgcmds/pkgadd pkgcmds/pkgrm pkgcmds/installf
	pkgcmds/pkginstall pkgcmds/pkgremove
	pkgcmds/pkgchk pkgcmds/pkgmk pkgcmds/pkgproto"

echo "== generating per-directory Makefiles (mk.config.amix) =="
for d in $SUBDIRS; do
	{
		echo "TOPDIR=$TOP"
		cat "$TOP/mk.config.amix"
		cat "$TOP/$d/Makefile.mk"
	} > "$TOP/$d/Makefile"
done

# Clean everything FIRST: the pkgcmds clean targets also remove
# ../../version/version.o, so interleaving clean+build per directory
# would delete version.o after it was built.
echo "== cleaning =="
for d in $SUBDIRS; do
	make -C "$TOP/$d" clean >/dev/null
done

echo "== building =="
for d in $SUBDIRS; do
	echo "--- $d"
	make -C "$TOP/$d" all
done

# ------------------------------------------------------------------
# 5. Collect and verify binaries
# ------------------------------------------------------------------
echo "== collecting binaries =="
BIN="$TOP/build-amix/bin"
SADM="$TOP/build-amix/sadm-helpers"

cp "$TOP/pkgcmds/pkginfo/pkginfo"     "$BIN/"
cp "$TOP/pkgcmds/pkgparam/pkgparam"   "$BIN/"
cp "$TOP/pkgcmds/pkgtrans/pkgtrans"   "$BIN/"
cp "$TOP/pkgcmds/pkgadd/pkgadd"       "$BIN/"
cp "$TOP/pkgcmds/pkgrm/pkgrm"         "$BIN/"
cp "$TOP/pkgcmds/installf/installf"   "$BIN/"
cp "$TOP/pkgcmds/pkgchk/pkgchk"       "$BIN/"
cp "$TOP/pkgcmds/pkgmk/pkgmk"         "$BIN/"
cp "$TOP/pkgcmds/pkgproto/pkgproto"   "$BIN/"
ln -sf pkgadd   "$BIN/pkgask"
ln -sf installf "$BIN/removef"
cp "$TOP/pkgcmds/pkginstall/pkginstall" "$SADM/"
cp "$TOP/pkgcmds/pkgremove/pkgremove"   "$SADM/"

m68k-cbm-sysv4-strip "$BIN"/pkginfo "$BIN"/pkgparam "$BIN"/pkgtrans \
	"$BIN"/pkgadd "$BIN"/pkgrm "$BIN"/installf "$BIN"/pkgchk \
	"$BIN"/pkgmk "$BIN"/pkgproto "$SADM"/pkginstall "$SADM"/pkgremove \
	2>/dev/null || echo "(strip failed; binaries left unstripped)"

# ------------------------------------------------------------------
# 5b. ds-repro: standalone datastream-reader reproducer (debug aid,
#     see ds-repro.c header; run on the box as
#     "DS_DEBUG=1 ds-repro <stream.pkg> <PKGINST> 2>trace")
# ------------------------------------------------------------------
echo "== building ds-repro =="
"$TOP/amix-cc" -O -c 	-I"$TOP/sslstub" -I"$TOP/compat" -D_XOPEN_SOURCE 	-I"$TOP/hdrs" -I"$TOP/libpkg" -I"$TOP/libgendb" 	"$TOP/ds-repro.c" -o "$TOP/build-amix/ds-repro.o"
m68k-cbm-sysv4-gcc "$TOP/build-amix/ds-repro.o" 	-L"$TOP/libinst" -linst -L"$TOP/libpkg" -lpkg 	-L"$TOP/libgendb" -lgendb -L"$TOP/libadm" -ladm 	-L"$TOP/build-amix/lib" -lamix -lc 	-o "$TOP/build-amix/ds-repro"
rm -f "$TOP/build-amix/ds-repro.o"

# ------------------------------------------------------------------
# 5c. probe-early: on-box probe for the early pkgremove flow
#     (mnttab parse -> get_mntinfo -> ocfile ladder -> temp image
#     write); see probe-early.c.  Run: DS_DEBUG=1 probe-early 2>&1
# ------------------------------------------------------------------
echo "== building probe-early =="
"$TOP/amix-cc" -O -c 	-I"$TOP/sslstub" -I"$TOP/compat" -D_XOPEN_SOURCE 	-I"$TOP/hdrs" -I"$TOP/libpkg" -I"$TOP/libgendb" 	-I"$TOP/libspmizones" 	"$TOP/probe-early.c" -o "$TOP/build-amix/probe-early.o"
m68k-cbm-sysv4-gcc "$TOP/build-amix/probe-early.o" 	-L"$TOP/libinst" -linst -L"$TOP/libpkg" -lpkg 	-L"$TOP/libgendb" -lgendb -L"$TOP/libadm" -ladm 	-L"$TOP/build-amix/lib" -lamix -lc 	-o "$TOP/build-amix/probe-early"
rm -f "$TOP/build-amix/probe-early.o"

echo "== verification =="
fail=0
for f in "$BIN"/pkginfo "$BIN"/pkgparam "$BIN"/pkgtrans "$BIN"/pkgadd \
	 "$BIN"/pkgrm "$BIN"/installf "$BIN"/pkgchk "$BIN"/pkgmk \
	 "$BIN"/pkgproto "$SADM"/pkginstall "$SADM"/pkgremove \
	 "$TOP/build-amix/ds-repro" "$TOP/build-amix/probe-early"; do
	t=$(file -b "$f")
	case "$t" in
	*"ELF 32-bit MSB"*m68k*) printf '%-12s OK  %s\n' "$(basename "$f")" "$t" ;;
	*) printf '%-12s BAD %s\n' "$(basename "$f")" "$t"; fail=1 ;;
	esac
	# DT_NEEDED must reference the guest libc by its SONAME only -
	# any absolute host path baked in makes the guest kernel SIGKILL
	# the binary at exec (dangling-DT_NEEDED trap).
	needed=$(m68k-cbm-sysv4-objdump -p "$f" 2>/dev/null | awk '/NEEDED/{print $2}')
	if [ "$needed" != "/usr/lib/libc.so.1" ]; then
		printf '%-12s BAD NEEDED: %s\n' "$(basename "$f")" "$needed"
		fail=1
	fi
done
# ------------------------------------------------------------------
# 6. Switch-dispatch invariant (kat-verify.sh pattern, see
#    src/contents-fsck/tests/): for every "movew %pc@(A,...)" jump-
#    table fetch, the following "jmp %pc@(B,...)" must satisfy A == B.
#    Equal only when the 4-byte .swbeg filler was emitted; without it
#    every switch case is entered 4 bytes late (stale flags).
# ------------------------------------------------------------------
echo "== switch-dispatch invariant =="
total_pairs=0
for f in "$BIN"/pkginfo "$BIN"/pkgadd "$SADM"/pkginstall; do
	out=$(m68k-cbm-sysv4-objdump -d "$f" 2>/dev/null | awk '
	function norm(a) {
		while (length(a) > 8)
			a = substr(a, 2)
		return a
	}
	/movew %pc@\(/ {
		if (match($0, /%pc@\([0-9a-f]+/)) {
			fetch = norm(substr($0, RSTART + 5, RLENGTH - 5))
			want = 1
			next
		}
	}
	want == 1 && /jmp %pc@\(/ {
		if (match($0, /%pc@\([0-9a-f]+/)) {
			jmpb = norm(substr($0, RSTART + 5, RLENGTH - 5))
			pairs++
			if (jmpb != fetch)
				badpairs++
		}
		want = 0
	}
	END { printf("%d %d", pairs, badpairs + 0) }')
	pairs=${out% *}
	bad=${out#* }
	printf '%-12s %s dispatch pair(s), %s mismatched\n' 		"$(basename "$f")" "$pairs" "$bad"
	total_pairs=$((total_pairs + pairs))
	[ "$bad" = 0 ] || fail=1
done
if [ "$total_pairs" -eq 0 ]; then
	echo "WARNING: no switch dispatch pairs found at all (check objdump pattern)"
	fail=1
fi

ls -l "$BIN" "$SADM"
exit $fail
